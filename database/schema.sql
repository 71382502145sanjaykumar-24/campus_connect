-- 12. Assignments Table
CREATE TABLE IF NOT EXISTS Assignment (
  id VARCHAR(36) PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  subjectId VARCHAR(36) NOT NULL,
  facultyId VARCHAR(36) NOT NULL,
