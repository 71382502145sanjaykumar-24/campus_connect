-- CampusConnect: Smart College Management System
-- Complete MySQL 8.0 Relational Database Schema DDL

CREATE DATABASE IF NOT EXISTS campusconnect CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE campusconnect;

-- 1. Users Table
CREATE TABLE IF NOT EXISTS User (
  id VARCHAR(36) PRIMARY KEY,
  email VARCHAR(191) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL,
  role VARCHAR(32) NOT NULL DEFAULT 'STUDENT',
  firstName VARCHAR(100) NOT NULL,
  lastName VARCHAR(100) NOT NULL,
  phone VARCHAR(20) NULL,
  avatar VARCHAR(255) NULL,
  isActive BOOLEAN NOT NULL DEFAULT TRUE,
  resetPasswordToken VARCHAR(255) NULL,
  resetPasswordExpires DATETIME NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_user_role (role),
  INDEX idx_user_email (email)
) ENGINE=InnoDB;

-- 2. Departments Table
CREATE TABLE IF NOT EXISTS Department (
  id VARCHAR(36) PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  description TEXT NULL,
  hodName VARCHAR(100) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 3. Courses Table
CREATE TABLE IF NOT EXISTS Course (
  id VARCHAR(36) PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  degree VARCHAR(50) NOT NULL,
  durationYears INT NOT NULL DEFAULT 4,
  departmentId VARCHAR(36) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (departmentId) REFERENCES Department(id) ON DELETE CASCADE,
  INDEX idx_course_dept (departmentId)
) ENGINE=InnoDB;

-- 4. Subjects Table
CREATE TABLE IF NOT EXISTS Subject (
  id VARCHAR(36) PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  semester INT NOT NULL DEFAULT 1,
  credits INT NOT NULL DEFAULT 3,
  departmentId VARCHAR(36) NOT NULL,
  courseId VARCHAR(36) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (departmentId) REFERENCES Department(id) ON DELETE CASCADE,
  FOREIGN KEY (courseId) REFERENCES Course(id) ON DELETE SET NULL,
  INDEX idx_subject_dept (departmentId),
  INDEX idx_subject_sem (semester)
) ENGINE=InnoDB;

-- 5. Students Table
CREATE TABLE IF NOT EXISTS Student (
  id VARCHAR(36) PRIMARY KEY,
  userId VARCHAR(36) NOT NULL UNIQUE,
  registerNumber VARCHAR(50) NOT NULL UNIQUE,
  studentId VARCHAR(50) NOT NULL UNIQUE,
  departmentId VARCHAR(36) NOT NULL,
  courseId VARCHAR(36) NOT NULL,
  year INT NOT NULL DEFAULT 1,
  semester INT NOT NULL DEFAULT 1,
  section VARCHAR(10) NOT NULL DEFAULT 'A',
  dateOfJoining DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  dob DATETIME NULL,
  gender VARCHAR(20) NULL,
  bloodGroup VARCHAR(10) NULL,
  address TEXT NULL,
  guardianName VARCHAR(100) NULL,
  guardianPhone VARCHAR(20) NULL,
  cgpa DOUBLE NOT NULL DEFAULT 0.0,
  skills TEXT NULL,
  certifications TEXT NULL,
  projects TEXT NULL,
  achievements TEXT NULL,
  resumeUrl VARCHAR(255) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (departmentId) REFERENCES Department(id) ON DELETE CASCADE,
  FOREIGN KEY (courseId) REFERENCES Course(id) ON DELETE CASCADE,
  INDEX idx_student_dept_sem (departmentId, semester),
  INDEX idx_student_reg (registerNumber)
) ENGINE=InnoDB;

-- 6. Faculty Table
CREATE TABLE IF NOT EXISTS Faculty (
  id VARCHAR(36) PRIMARY KEY,
  userId VARCHAR(36) NOT NULL UNIQUE,
  facultyId VARCHAR(50) NOT NULL UNIQUE,
  departmentId VARCHAR(36) NOT NULL,
  designation VARCHAR(100) NOT NULL,
  qualification VARCHAR(100) NULL,
  specialization VARCHAR(150) NULL,
  joiningDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  officeRoom VARCHAR(50) NULL,
  cabinPhone VARCHAR(20) NULL,
  responsibilities TEXT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (departmentId) REFERENCES Department(id) ON DELETE CASCADE,
  INDEX idx_faculty_dept (departmentId)
) ENGINE=InnoDB;

-- 7. Attendance Table
CREATE TABLE IF NOT EXISTS Attendance (
  id VARCHAR(36) PRIMARY KEY,
  studentId VARCHAR(36) NOT NULL,
  subjectId VARCHAR(36) NOT NULL,
  date DATETIME NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PRESENT',
  session VARCHAR(20) NOT NULL DEFAULT 'FORENOON',
  remarks VARCHAR(255) NULL,
  markedByFacultyId VARCHAR(36) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (studentId) REFERENCES Student(id) ON DELETE CASCADE,
  FOREIGN KEY (subjectId) REFERENCES Subject(id) ON DELETE CASCADE,
  INDEX idx_att_student (studentId),
  INDEX idx_att_date (date)
) ENGINE=InnoDB;

-- 8. Internal Marks Table
CREATE TABLE IF NOT EXISTS InternalMark (
  id VARCHAR(36) PRIMARY KEY,
  studentId VARCHAR(36) NOT NULL,
  subjectId VARCHAR(36) NOT NULL,
  examType VARCHAR(50) NOT NULL,
  maxMarks DOUBLE NOT NULL DEFAULT 50.0,
  marksObtained DOUBLE NOT NULL DEFAULT 0.0,
  remarks VARCHAR(255) NULL,
  enteredByFacultyId VARCHAR(36) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (studentId) REFERENCES Student(id) ON DELETE CASCADE,
  FOREIGN KEY (subjectId) REFERENCES Subject(id) ON DELETE CASCADE,
  INDEX idx_mark_student (studentId)
) ENGINE=InnoDB;

-- 9. Semester Results Table
CREATE TABLE IF NOT EXISTS SemesterResult (
  id VARCHAR(36) PRIMARY KEY,
  studentId VARCHAR(36) NOT NULL,
  semester INT NOT NULL,
  totalCredits INT NOT NULL DEFAULT 24,
  earnedCredits INT NOT NULL DEFAULT 24,
  gpa DOUBLE NOT NULL DEFAULT 0.0,
  cgpa DOUBLE NOT NULL DEFAULT 0.0,
  resultStatus VARCHAR(20) NOT NULL DEFAULT 'PASS',
  publishedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  remarks VARCHAR(255) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (studentId) REFERENCES Student(id) ON DELETE CASCADE,
  INDEX idx_result_student (studentId)
) ENGINE=InnoDB;

-- 10. Timetables Table
CREATE TABLE IF NOT EXISTS Timetable (
  id VARCHAR(36) PRIMARY KEY,
  departmentId VARCHAR(36) NOT NULL,
  courseId VARCHAR(36) NOT NULL,
  semester INT NOT NULL DEFAULT 1,
  section VARCHAR(10) NOT NULL DEFAULT 'A',
  dayOfWeek VARCHAR(20) NOT NULL,
  startTime VARCHAR(20) NOT NULL,
  endTime VARCHAR(20) NOT NULL,
  subjectId VARCHAR(36) NOT NULL,
  facultyId VARCHAR(36) NOT NULL,
  roomNumber VARCHAR(50) NOT NULL,
  isLab BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (departmentId) REFERENCES Department(id) ON DELETE CASCADE,
  FOREIGN KEY (courseId) REFERENCES Course(id) ON DELETE CASCADE,
  FOREIGN KEY (subjectId) REFERENCES Subject(id) ON DELETE CASCADE,
  FOREIGN KEY (facultyId) REFERENCES Faculty(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 11. Examinations Table
CREATE TABLE IF NOT EXISTS Examination (
  id VARCHAR(36) PRIMARY KEY,
  examName VARCHAR(150) NOT NULL,
  semester INT NOT NULL,
  academicYear VARCHAR(30) NOT NULL,
